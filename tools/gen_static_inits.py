#!/usr/bin/env python3
"""gen_static_inits.py - register the PS2 build's hand-written static
initialisers with the port's start-up (include/pc_static_init.h).

  1. Writes src/main/static_init_order.inc: the PS2 __CTOR_LIST__ entries
     (decomp ref/ctors.json), the order __do_global_ctors used.
  2. After each function of src/game and src/engine whose `// FUNC 0x...`
     marker is in that list and whose definition exists in the port, adds
     PC_STATIC_INIT(name, 0xADDR); (once; reruns change nothing).

  python tools/gen_static_inits.py [--dry-run]
"""
import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PORT = os.path.normpath(os.path.join(HERE, ".."))
DECOMP = os.path.normpath(os.path.join(PORT, "..", "decomp", "core_gt3enhanced"))
MARKER = re.compile(r"^// FUNC (0x[0-9A-Fa-f]{8}) (\S+)")


def function_end(lines, start, name):
    """Index of the line with the closing brace of the definition of `name`
    that follows line `start`, or None if only comments follow."""
    i = start + 1
    short = name.split("::")[-1]
    while i < len(lines):
        s = lines[i].strip()
        if s.startswith("// FUNC"):
            return None
        if s == "" or s.startswith("//") or s.startswith("/*") or s.startswith("*"):
            i += 1
            continue
        if short + "(" not in s.replace(" (", "("):
            return None
        break
    depth = 0
    seen = False
    while i < len(lines):
        code = re.sub(r"//.*$", "", lines[i])
        code = re.sub(r'"([^"\\]|\\.)*"', '""', code)
        for ch in code:
            if ch == "{":
                depth += 1
                seen = True
            elif ch == "}":
                depth -= 1
                if seen and depth == 0:
                    return i
        i += 1
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    ctors = [int(a, 16) for a in json.load(open(os.path.join(DECOMP, "ref", "ctors.json")))["ctors"]]
    order = os.path.join(PORT, "src", "main", "static_init_order.inc")
    os.makedirs(os.path.dirname(order), exist_ok=True)
    if not args.dry_run:
        with open(order, "w", newline="\n") as f:
            f.write("/* Generated by tools/gen_static_inits.py: the PS2 __CTOR_LIST__ entries\n"
                    " * (decomp ref/ctors.json) in list order.  __do_global_ctors ran them\n"
                    " * from the last to the first. */\n")
            for a in ctors:
                f.write("0x%08X,\n" % a)

    wanted = set(ctors)
    added = found = 0
    for tree in ("src/game", "src/engine"):
        for dp, dn, fn in os.walk(os.path.join(PORT, tree)):
            for n in fn:
                if not n.endswith((".cpp", ".c")):
                    continue
                path = os.path.join(dp, n)
                text = open(path, encoding="utf-8", errors="surrogateescape").read()
                lines = text.split("\n")
                inserts = []
                for i, l in enumerate(lines):
                    m = MARKER.match(l)
                    if not m or int(m.group(1), 16) not in wanted:
                        continue
                    name = m.group(2)
                    end = function_end(lines, i, name)
                    if end is None:
                        continue
                    found += 1
                    reg = "PC_STATIC_INIT(%s, %s);" % (name, m.group(1).upper().replace("0X", "0x"))
                    if end + 1 < len(lines) and lines[end + 1].strip() == reg:
                        continue
                    inserts.append((end + 1, reg))
                for at, reg in reversed(inserts):
                    lines.insert(at, reg)
                    added += 1
                    print("%s: %s" % (os.path.relpath(path, PORT), reg))
                if inserts and not args.dry_run:
                    with open(path, "w", encoding="utf-8", errors="surrogateescape", newline="\n") as f:
                        f.write("\n".join(lines))
    print("%d of %d list entries are hand-written initialisers in the port; %d registrations added"
          % (found, len(ctors), added))
    return 0


if __name__ == "__main__":
    sys.exit(main())
