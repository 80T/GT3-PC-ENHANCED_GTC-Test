uint32_t upper(uint32_t c)
{
    if (c >= 'a' && c <= 'z')
        return c - 32;
    if (c >= 0xE0 && c <= 0xFE && c != 0xF7)
        return c - 32;
    if (c == 0xFF)
        return 0x178;
    if (c >= 0x100 && c <= 0x17F) {
        /* pairs: upper case even, except 0x139 .. 0x148 and 0x179 .. 0x17E (odd) */
        const bool oddUpper = (c >= 0x139 && c <= 0x148) || (c >= 0x179 && c <= 0x17E);
        if (c == 0x130 || c == 0x131 || c == 0x138 || c == 0x149 || c == 0x17F)
            return c;
        return oddUpper ? ((c & 1) ? c : c - 1) : ((c & 1) ? c - 1 : c);
    }
    if (c >= 0x430 && c <= 0x44F)
        return c - 32;
    if (c >= 0x450 && c <= 0x45F)
        return c - 80;
    return c;
}


bool narrow_glyph(uint32_t c, Glyph *g)
{
    return narrow_glyph_at(c, g, 0);
}

bool wide_range(uint32_t c)
{
    return (c >= 0x3000 && c <= 0x30FF) || (c >= 0x31F0 && c <= 0x31FF) || (c >= 0x3400 && c <= 0x4DBF) ||
           (c >= 0x4E00 && c <= 0x9FFF) || (c >= 0xFF00 && c <= 0xFFEF);
}

