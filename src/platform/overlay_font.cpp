/* ---- PC (2026-11-16): the interface's languages (platform/ui_text.h) ----
 * The strings are UTF-8.  The letters of French, German, Italian, Spanish,
 * Portuguese, Polish and Russian upper case in the same 5 x 7 style, an
 * accent in rows -3 and -2, a row free over the letter (the line is 12 rows:
 * the line above's cedilla ends at its row 8, our -4), a cedilla or ogonek in
 * the two rows below; every other
 * character (Japanese) from MS Gothic's own 12 pixel bitmaps (its embedded
 * strikes, not anti-aliased: the same pixel look), 6 or 12 font pixels wide
 * (one or two cells), its 12 rows over the line's (row -3 .. 8: the
 * highlight's band).  tools/lang_sync links this file (the characters
 * the panels' strings may use). */

