bool narrow_glyph_at(uint32_t c, Glyph *g, int depth)
{
    if (c < 0x80) {
        const char *p = c != 0 ? strchr(kGlyphChars, (int)c) : nullptr;
        if (p == nullptr)
            return false;
        memset(g, 0, sizeof(*g));
        memcpy(g->rows + 3, kGlyphs[p - kGlyphChars], 7);
        return true;
    }
    for (const Own &o : kOwnGlyphs)
        if (o.cp == c) {
            memset(g, 0, sizeof(*g));
            memcpy(g->rows + 3, o.rows, 8);
            return true;
        }
    if (depth > 1)
        return false;
    for (const Composed &k : kComposed)
        if (k.cp == c) {
            if (k.base == ' ') {
                memset(g, 0, sizeof(*g));
                return true;
            }
            if (!narrow_glyph_at(k.base, g, depth + 1))
                return false;
            g->rows[0] |= kMarks[k.mark][0];
            g->rows[1] |= kMarks[k.mark][1];
            g->rows[10] |= kMarks[k.mark][2];
            g->rows[11] |= kMarks[k.mark][3];
            return true;
        }
    return false;
}

